#!/usr/bin/env node
/**
 * Keeps Tailwind CSS v4 off the class names Once UI ships.
 *
 * Tailwind puts its utilities in a layer above Once UI's, so a class both of
 * them define takes Tailwind's rule, on Once UI's elements too, as soon as an
 * app's source mentions it. That breaks two ways: a name with another meaning
 * (Tailwind's `p-4` is 1rem; 3.0 spells Once UI's spacing out as
 * `padding-4` so none is left), and a name with the same meaning whose
 * breakpoint form Tailwind's rule outranks (`flex-row` beside Once UI's
 * `s-flex-column` keeps a row on a phone).
 *
 * This compiles every class name in dist/css/styles.css and tokens.css with
 * Tailwind and the adapter, and writes the ones Tailwind would generate into
 * tailwind/tailwind.css as `@source not inline(…)`. Tailwind then never
 * generates them, and an app's `className="flex-row"` gets Once UI's rule,
 * which does the same. Variants (`hover:flex-row`, `md:flex-row`) are other
 * class names and still work.
 *
 * Fails when a spacing, offset or grid-column name is among them: those mean
 * something else in Tailwind, and blocking them would change an app's
 * Tailwind classes, so they have to be renamed in utilities.spec.mjs instead.
 *
 *   node scripts/tailwind-overlap.mjs           rewrite the list
 *   node scripts/tailwind-overlap.mjs --check   fail if it is stale (CI)
 *
 * Needs `pnpm build` first (it reads dist/css).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "tailwindcss";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ADAPTER = join(ROOT, "tailwind/tailwind.css");
const START = "/* tailwind-overlap:start";
const END = "/* tailwind-overlap:end */";
const TW = dirname(createRequire(import.meta.url).resolve("tailwindcss/package.json"));

/** Tailwind's names whose meaning differs from Once UI's, by family. */
export const MUST_RENAME =
  /^(p|px|py|pt|pr|pb|pl|m|mx|my|mt|mr|mb|ml|top|right|bottom|left|inset|gap|columns|grid-cols|space-[xy])-/;

export function classNames(css) {
  const names = new Set();
  for (const m of css.matchAll(/\.((?:[a-zA-Z_]|\\.)(?:[\w-]|\\.)*)/g)) {
    const name = m[1].replace(/\\(.)/g, "$1");
    if (!/^\d/.test(name)) names.add(name);
  }
  return [...names].sort();
}

async function tailwind(adapter) {
  const load = async (id, base) => {
    const file =
      id === "tailwindcss"
        ? join(TW, "index.css")
        : id.startsWith("tailwindcss/")
          ? join(TW, id.slice("tailwindcss/".length))
          : join(base, id);
    return { path: file, base: dirname(file), content: readFileSync(file, "utf8") };
  };
  // The adapter without its own block list, so the list is computed afresh.
  const own = adapter.replace(
    new RegExp(`\\n?${escapeRe(START)}[\\s\\S]*?${escapeRe(END)}\\n?`),
    "\n",
  );
  return compile(`${own}\n@import "tailwindcss";\n`, { base: ROOT, loadStylesheet: load });
}

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");

export async function overlap() {
  const css = ["styles.css", "tokens.css"]
    .map((f) => readFileSync(join(ROOT, "dist/css", f), "utf8"))
    .join("\n");
  const adapter = readFileSync(ADAPTER, "utf8");
  const compiler = await tailwind(adapter);
  const shared = [];
  for (const name of classNames(css)) {
    const out = compiler.build([name]);
    const selector = `.${name.replace(/[^\w-]/g, (c) => `\\${c}`)}`;
    if (out.includes(`${selector} {`) || out.includes(`${selector}:`)) shared.push(name);
  }
  return { shared, adapter };
}

function block(names) {
  const lines = [];
  let line = "";
  for (const name of names) {
    if (line && line.length + name.length > 56) {
      lines.push(line);
      line = "";
    }
    line += (line ? " " : "") + name;
  }
  if (line) lines.push(line);
  return (
    `${START}\n` +
    " * Generated by scripts/tailwind-overlap.mjs: the class names Once UI and\n" +
    " * Tailwind both define. Tailwind does not generate them, so they keep Once\n" +
    " * UI's rule, which does the same thing, and its breakpoint forms still win.\n" +
    " */\n" +
    // One directive a line: a CSS string cannot hold a newline.
    lines.map((l) => `@source not inline("${l}");\n`).join("") +
    END
  );
}

const invokedDirectly = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (invokedDirectly) {
  const { shared, adapter } = await overlap();
  const renamed = shared.filter((n) => MUST_RENAME.test(n));
  if (renamed.length) {
    console.error(
      `tailwind-overlap: Tailwind gives these Once UI classes another meaning; rename them in utilities.spec.mjs:\n  ${renamed.join(" ")}`,
    );
    process.exit(1);
  }
  const next = adapter.replace(
    new RegExp(`${escapeRe(START)}[\\s\\S]*?${escapeRe(END)}`),
    block(shared),
  );
  if (!next.includes(START)) {
    console.error(`tailwind-overlap: no "${START}" marker in tailwind/tailwind.css`);
    process.exit(1);
  }
  if (process.argv.includes("--check")) {
    if (next !== adapter) {
      console.error(
        "tailwind-overlap: tailwind/tailwind.css is stale; run `node scripts/tailwind-overlap.mjs`.",
      );
      process.exit(1);
    }
    console.log(`tailwind-overlap: ${shared.length} shared class names, all kept off Tailwind`);
  } else {
    writeFileSync(ADAPTER, next);
    console.log(
      `tailwind-overlap: ${shared.length} shared class names written to tailwind/tailwind.css`,
    );
  }
}
