/**
 * Generates `src/icons/data.ts`: the SVG data for Once UI's built-in icons.
 *
 * Since 3.0 the built-ins are Once UI's own icons, drawn as code in
 * https://github.com/once-ui-system/icons (MIT). This script copies the
 * `rounded` line set from that repo's build (`dist/data/index.js`) into core,
 * so core has no runtime dependency on the icons package and nothing to fetch.
 *
 * Every icon in the set shares one root (24 grid, 1.5 stroke, round caps and
 * joins), so the root is written once and each icon carries only its paths.
 * `[data-border="conservative"]` squares the caps and joins in CSS
 * (src/styles/icons.scss); the set's own drawn conservative and playful
 * geometry comes with per-shape data in 3.1.
 *
 * Run: pnpm generate-icons --from <path to a built clone of once-ui-system/icons>
 *      (or set ONCE_ICONS_DIR). Then run `pnpm --filter @once-ui-system/native sync:icons`.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const argIndex = process.argv.indexOf("--from");
const from = argIndex > -1 ? process.argv[argIndex + 1] : process.env.ONCE_ICONS_DIR;
if (!from) {
  console.error("Pass --from <icons repo> (built with `npm run build`) or set ONCE_ICONS_DIR.");
  process.exit(1);
}

const entry = path.resolve(from, "dist/data/index.js");
if (!fs.existsSync(entry)) {
  console.error(`${entry} not found: run \`npm run build\` in the icons repo first.`);
  process.exit(1);
}

const { iconData } = await import(pathToFileURL(entry).href);
const set = iconData.rounded;
const names = Object.keys(set).sort();

const roots = new Set(names.map((name) => JSON.stringify(set[name].line.attr)));
if (roots.size !== 1) throw new Error(`Expected one shared root, found ${roots.size}`);
const root = JSON.parse([...roots][0]);
// Icon components are decorative unless the caller names them; Icon sets aria itself.
delete root["aria-hidden"];

const body = names
  .map(
    (name) =>
      `  ${name}: { tag: "svg", attr: line, child: ${JSON.stringify(set[name].line.child)} },`,
  )
  .join("\n");

fs.writeFileSync(
  path.join(ROOT, "..", "src", "icons", "data.ts"),
  `// Generated by scripts/generate-icons.mjs — do not edit by hand.
// Once UI's own icons (once-ui-system/icons, MIT): see ./ATTRIBUTION.md
import type { IconNode } from "./renderIcon.js";

const line = ${JSON.stringify(root)};

export const iconData = {
${body}
} satisfies Record<string, IconNode>;
`,
);
// Written in Biome's format, so the lint gate stays at its baseline.
execFileSync("npx", ["biome", "format", "--write", "src/icons/data.ts"], {
  cwd: path.join(ROOT, ".."),
  stdio: "ignore",
});
console.log(`Generated ${names.length} icons from ${path.relative(process.cwd(), entry)}`);
