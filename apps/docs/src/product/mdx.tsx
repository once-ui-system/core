type MDXComponents = React.ComponentProps<typeof MDXRemote>["components"];

type CustomMDXProps = Omit<MDXRemoteProps, "components"> & {
  components?: Partial<MDXComponents>;
};

export function CustomMDX(props: CustomMDXProps) {
  return (
    <MDXRemote
      {...props}
      // `blockJS: false` is load-bearing: next-mdx-remote 6 blocks JS expressions
      // in MDX by default, and every doc page passes props like `codes={[…]}`.
      options={{
        blockJS: false,
        ...(props.options ?? {}),
        mdxOptions: {
          ...(props.options?.mdxOptions ?? {}),
          remarkPlugins: [remarkGfm, ...(props.options?.mdxOptions?.remarkPlugins ?? [])],
        },
      }}
      components={{
        ...mdxComponents,
        ...(props.components || {}),
      }}
    />
  );
}
