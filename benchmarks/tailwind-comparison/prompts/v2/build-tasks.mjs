#!/usr/bin/env node
// Builds prompts/v2/tasks.json from briefs.json + seed.json, so every task's
// prompt carries the same product and the slice of seed data it needs.
//   node prompts/v2/build-tasks.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
const briefs = read("briefs.json");
const seed = read("seed.json");

const tasks = briefs.tasks.map(({ brief, seed: keys, interaction, views, ...task }) => {
  const data = Object.fromEntries(keys.map((k) => [k, seed[k]]));
  const prompt = `${brief}\n\nUse this data for the content (define it in the code; you may put it in \`lib/data.ts\`):\n\n\`\`\`json\n${JSON.stringify(data, null, 2)}\n\`\`\``;
  // The rebrand task's identity, for the gates' brand check (recorded, not gated).
  return { ...task, output: "multi", prompt, ...(keys.includes("brand") ? { brand_check: seed.brand } : {}) };
});
const interactions = Object.fromEntries(briefs.tasks.map((t) => [String(t.id), t.interaction]));
// Extra named views per task (Pro set, rebrand): each is screenshotted at every
// viewport for the side-by-side gallery. Recorded, never gated.
const views = Object.fromEntries(briefs.tasks.filter((t) => t.views).map((t) => [String(t.id), t.views]));
const out = {
  $comment: "GENERATED by build-tasks.mjs from briefs.json and seed.json. Edit those, then rebuild.",
  generation: briefs.generation,
  tasks,
  interactions,
  views,
};
fs.writeFileSync(path.join(dir, "tasks.json"), `${JSON.stringify(out, null, 2)}\n`);
console.log(`${tasks.length} tasks -> prompts/v2/tasks.json`);
