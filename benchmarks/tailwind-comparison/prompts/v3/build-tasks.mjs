#!/usr/bin/env node
// Builds prompts/v3/tasks.json: the Bench v2 brand pilot. Each base task from
// prompts/v2/tasks.json is cloned once per brand sheet in brands.json, with the
// sheet appended to its prompt, the rebrand task's theme files editable, and the
// sheet as the gates' brand check (recorded, never gated). Task ids are
// <base id> * 100 + <brand index + 1>, so 101-103 are t1 in brands 1-3.
//   node prompts/v3/build-tasks.mjs [--base 1]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const v2 = JSON.parse(fs.readFileSync(path.join(dir, "../v2/tasks.json"), "utf8"));
const { brands } = JSON.parse(fs.readFileSync(path.join(dir, "brands.json"), "utf8"));
const baseIds = (process.argv.includes("--base") ? process.argv[process.argv.indexOf("--base") + 1] : "1").split(",").map(Number);
const editable = v2.tasks.find((t) => t.id === 9).editable;

const sheet = (b) =>
  [
    `Brand: build it in Lumen's visual identity below. Carry it through the design system's own theming (its theme tokens, config or provider), not one-off styles on each element, so every screen follows it.`,
    `- Personality: ${b.personality}.`,
    `- Brand colour ${b.brand_color}: primary buttons, the current navigation item, links and focus rings.`,
    `- Neutrals: ${b.neutral}.`,
    `- Corner radius: ${b.radius}.`,
    `- Headings in ${b.heading_font}; body text in ${b.body_font}.`,
    `- Default theme: ${b.default_theme}.`,
    `- Density: ${b.density}.`,
  ].join("\n");

const tasks = [];
const interactions = {};
const views = {};
for (const id of baseIds) {
  const base = v2.tasks.find((t) => t.id === id);
  brands.forEach((b, i) => {
    const nid = id * 100 + i + 1;
    const [brief, ...rest] = base.prompt.split("\n\nUse this data");
    tasks.push({
      ...base,
      id: nid,
      slug: `${base.slug}-${b.key}`,
      title: `${base.title} (${b.key} brand)`,
      set: "brand",
      editable,
      brand: b.key,
      prompt: `${brief}\n\n${sheet(b)}\n\nUse this data${rest.join("\n\nUse this data")}`,
      brand_check: b,
    });
    if (v2.interactions[String(id)]) interactions[String(nid)] = v2.interactions[String(id)];
    if (v2.views?.[String(id)]) views[String(nid)] = v2.views[String(id)];
  });
}
const out = { $comment: "GENERATED by build-tasks.mjs from ../v2/tasks.json and brands.json.", generation: v2.generation, tasks, interactions, views };
fs.writeFileSync(path.join(dir, "tasks.json"), `${JSON.stringify(out, null, 2)}\n`);
console.log(`${tasks.length} tasks -> prompts/v3/tasks.json`);
